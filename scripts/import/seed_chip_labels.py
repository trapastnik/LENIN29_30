"""Короткая подпись партии для чипа диаграммы Венна — `title_chip_ru`.

Полное название остаётся в карточке; на схеме оно не помещается. Зона
`design` доказала замером, что блоб «Белые» не вмещает свою длиннейшую
подпись **ни при каком положении чипа**: где есть вертикальный размах под
пять строк, подпись упирается в правый край кадра; где помещается по
ширине — размах 32 px, то есть одна строка из пяти. Перестановкой это
не чинится, блоб стоит у кромки, а подпись растёт вправо.

## Порог

`design` дала ориентир «не длиннее ~340 px, это примерно 24–26 знаков».
Второе с первым не сходится. По её же трём замерам ширина линейна:

    Бунд                                             4 знака   72 px
    Социал-демократическая партия Финляндии         39 знаков 390 px
    Украинская социал-демократическая рабочая партия 47 знаков 453 px

    ширина ≈ 36.6 px постоянных + 8.86 px на знак

Отсюда 340 px — это **34 знака**, а не 24–26. Модель проверяется счётом:
длиннее 34 знаков ровно **10 партий**, и `design` в том же письме называет
«десять подписей из 33». Значит порог 34, а «24–26» — описка.

Берём 34 и держим запас: ни одна подпись ниже не длиннее 27 знаков.

## Откуда берётся короткое имя

**Сначала — «Краткое название» из докс заказчика** (`aka_ru`): оно есть
у 16 партий, и это его слова, а не наши. «Кадеты», «Народные социалисты»,
«Комитет спасения», «Грузинские меньшевики» пришли оттуда.

**Аббревиатура — не ответ.** `abbr_ru` есть у 17 партий, но «УСДРП»
на схеме читается хуже, чем «Украинская СДРП»: посетитель у стенда
не расшифровывает. Аббревиатура годится внутри слова («СДП Финляндии»),
а не вместо него.

Запуск:  python3 scripts/import/seed_chip_labels.py
         python3 scripts/import/run_import.py --kind party
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PARTIES = ROOT / "public" / "content" / "parties"

MAX_CHIP = 34   # знаков; см. вывод порога в докстринге

# id → (короткая подпись, откуда взята)
CHIPS = {
    "ukrainskaya-sotsial-demokraticheskaya-ra": (
        "Украинская СДРП",
        "аббревиатура внутри слова, а не вместо него — пример самой design"),
    "alekseev-org": (
        "Добровольческая армия",
        "вторая половина двойного заголовка: под этим именем организация "
        "и известна, «Алексеевская» — первые два месяца из трёх лет"),
    "narodnie-socialists": (
        "Народные социалисты",
        "«Краткое название» заказчика"),
    "gruzinskaya-sotsial-demokraticheskaya-pa": (
        "Грузинские меньшевики",
        "«Краткое название» заказчика"),
    "sotsial-demokraticheskaya-partiya-finlya": (
        "СДП Финляндии",
        "страна остаётся словом: «СДПФ» на схеме не читается"),
    "muslim-socialists": (
        "Мусульманские соцкомитеты",
        "«социалистические» сокращено, но не выброшено — оно различающее"),
    "cadets": (
        "Кадеты",
        "«Краткое название» заказчика, и оно же общеупотребительное"),
    "belorusskaya-sotsialisticheskaya-gromada": (
        "Белорусская громада",
        "«социалистическая» выброшено: у громады нет омонимов, "
        "различать не от чего"),
    "union-constituent": (
        "Союз защиты Учред. собрания",
        "«Союз защиты» из докс не годится — столкнётся с «Союзом защиты "
        "Родины и свободы», который стоит рядом на диаграмме"),
    "committee-salvation": (
        "Комитет спасения",
        "«Краткое название» заказчика"),
}


def main() -> int:
    written = skipped = 0
    problems = []
    for eid, (chip, why) in sorted(CHIPS.items()):
        card = PARTIES / ("%s.json" % eid)
        if not card.exists():
            problems.append("нет справки %s" % eid)
            continue
        if len(chip) > MAX_CHIP:
            problems.append("%s: подпись %d знаков, порог %d"
                            % (eid, len(chip), MAX_CHIP))
            continue
        path = PARTIES / ("%s.patch.json" % eid)
        patch = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
        if patch.get("title_chip_ru") == chip:
            skipped += 1
            continue
        patch["schema"] = 1
        patch["title_chip_ru"] = chip
        path.write_text(json.dumps(patch, ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")
        written += 1
        print("  %-42s %-28s %s" % (eid, chip, why[:52]))

    # Столкновений быть не должно: две подписи-близнеца на одной диаграмме
    # хуже длинной — посетитель не поймёт, какая из них какая.
    seen = {}
    for eid, (chip, _) in CHIPS.items():
        if chip in seen:
            problems.append("подпись «%s» у %s и %s" % (chip, seen[chip], eid))
        seen[chip] = eid

    print("подписей записано: %d, уже стояли: %d" % (written, skipped))
    for p in problems:
        print("  ! %s" % p)
    if problems:
        return 1
    print("дальше: python3 scripts/import/run_import.py --kind party")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
