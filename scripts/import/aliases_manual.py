"""Кураторские решения по алиасам: то, что автомат решить не вправе.

Две категории.

**Спорные** — фраза одинаково похожа на две сущности, и автомат честно
отказывается выбирать. Почти все такие пары породил формат заголовков
в индексах: «Российское Государство · А.В. Колчак» разбивается на части,
и часть «А. В. Колчак» сталкивается с персоной. В тексте «А. В. Колчака»
почти всегда человек, а государство называют «Российским государством» —
так и разводим.

**Ненайденные** — сущность в проекте есть, но называется иначе, чем в тексте:
партия «Белые» против оборота «Белого движения», государство «Польская
Республика» против «Польши».

`BY_KEY` покрывает все падежные формы разом: ключ огрублён, и «Колчака»,
«Колчаком», «Колчаку» попадают под одну строку. `EXACT` — для случаев,
где огрубление само склеивает разное: «Красные» (партия) и «Краснов»
(персона) дают один ключ `красн`, и различить их можно только по написанию.

⚠️ Чего здесь намеренно НЕТ: Германия, Австро-Венгрия, Османская империя,
Япония. Сущностей под них в проекте не заведено, а вести ссылку на
«Интервенцию Центральных держав» со слова «Германия» — значит открыть
посетителю карточку с другим названием. Такие упоминания остаются жирным
курсивом без ссылки: деградация визуально незаметна.

Также нет Финляндии и Грузии — там по две сущности на разные периоды
(Финляндская Республика и Финляндская Социалистическая Рабочая Республика;
Грузинская Демократическая Республика и ССР Грузия), и выбор зависит от даты
события. Вопрос музею, не машине.
"""

from __future__ import annotations

# Фраза-образец → сущность. Покрывает все падежные формы с тем же ключом.
BY_KEY = {
    # ── спорные: разводим человека и государство его имени
    "А. В. Колчак": "person:kolchak",
    "Российское Государство": "state:russian-state-kolchak",
    # РСДРП(б) — это именно большевики, «(б)» и есть различитель
    "РСДРП(б)": "party:bolsheviks",

    # ── есть в проекте под другим названием
    "Белое движение": "party:whites-general",
    "Польша": "state:polskaya-respublika",
    "Эстония": "state:estonskaya-respublika",
    "ЧСК": "state:czechoslovak-corps",
    "Советская Россия": "state:rsfsr",
    "Добровольческая армия": "party:alekseev-org",
}

# Точное написание → сущность. Для тех, кого огрубление ключа склеивает.
EXACT = {
    "Красные": "party:reds-general",
    "Красным": "party:reds-general",
    "красных": "party:reds-general",
    "Краснов": "person:krasnov",
    "Краснова": "person:krasnov",
    "Красновым": "person:krasnov",
    "Краснову": "person:krasnov",
}

# Фразы, которые автомат разрешать НЕ должен, даже если совпадение однозначно.
# Слишком общие: ссылка с них уводит в частность.
DENY = {
    "России", "Россия", "Российской империи", "империи",
    "армии", "армия", "партии", "партия", "правительства", "правительство",
}
