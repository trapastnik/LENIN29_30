"""Лагерь персоны по тексту справки.

В докс-справках личности поля «лагерь» нет вообще — заказчик его не заводил.
Единственный источник в поставке — регалии: они формульны («Лидер партии
большевиков», «Один из руководителей Белого движения на Юге России»), и по ним
принадлежность читается почти всегда.

`public/expo/people-data.js` в качестве источника не годится: это подборка
design-pass на 17 человек с тремя значениями `side`, куда всё небелое
и некрасное свалено в `green`. Там Авксентьев — «зелёный», хотя он один
из лидеров эсеров, а Пилсудский — «зелёный», хотя он глава Польши.
Расхождения с этим файлом печатаются в отчёт, чтобы их увидел человек.

Итог помечается `camp_source: "regalia"` — он получен разбором текста,
а не прислан заказчиком, и перебивается вручную через `<id>.patch.json`.
Неуверенный результат — `null`: пустой фильтр честнее неправильного.
"""

from __future__ import annotations

import re
from typing import Dict, List, Optional, Tuple

CAMPS = ("red", "white", "rev-dem", "national", "green")

# (лагерь, вес, шаблон). Вес 6 — прямое самоназвание движения или партии,
# 3 — институт, принадлежность которого однозначна, 1 — косвенный признак.
RULES: List[Tuple[str, int, str]] = [
    # ── красные
    ("red", 6, r"большевик"),
    ("red", 6, r"РКП\(б\)|РСДРП\(б\)|ВКП\(б\)"),
    ("red", 6, r"Рабоче-крестьянск\w+ Красной армии|РККА|Красной армии"),
    ("red", 3, r"Совет\w* народных комиссаров РСФСР|СНК РСФСР"),
    ("red", 3, r"ВЦИК|Всероссийск\w+ центральн\w+ исполнительн\w+"),
    ("red", 3, r"чрезвычайн\w+ комисси|ВЧК"),
    ("red", 3, r"народн\w+ комиссар\w*\s"),
    ("red", 3, r"реввоенсовет|Революционн\w+ военн\w+ совет"),
    ("red", 3, r"советск\w+ власти|Советской России"),
    ("red", 3, r"красн\w+ партизан|партизанск\w+ движени"),
    ("red", 6, r"Советск\w+ военачальник|Вооруженными Силами Республики"),
    ("red", 3, r"Народно-революционн\w+ арми"),
    ("red", 1, r"ССР|АССР|СССР|РСФСР"),
    # ── белые
    ("white", 6, r"Бел\w+ движени"),
    ("white", 6, r"Добровольческ\w+ арми"),
    ("white", 6, r"Вооруженным\w* силам\w* Юга России|ВСЮР"),
    ("white", 3, r"Русск\w+ арми"),
    ("white", 3, r"Российск\w+ государств"),
    ("white", 3, r"атаман\w*\s+\w*\s*казач\w+ войск|Войсков\w+ атаман"),
    ("white", 3, r"монархист"),
    ("white", 3, r"Верховн\w+ Правител"),
    # ── революционная демократия
    ("rev-dem", 6, r"социалистов-революционеров|эсер"),
    ("rev-dem", 6, r"меньшевик"),
    ("rev-dem", 6, r"народно-социалистическ|народн\w+ социалист"),
    ("rev-dem", 3, r"Учредительн\w+ собрани"),
    ("rev-dem", 3, r"Комуч|Комитет\w* членов"),
    ("rev-dem", 3, r"Временн\w+ правительств"),
    ("rev-dem", 3, r"Уфимск\w+ директори|Временн\w+ Всероссийск\w+ правительств"),
    ("rev-dem", 3, r"Временн\w+ Сибирск\w+ правительств|областничеств"),
    ("rev-dem", 1, r"Северн\w+ области"),
    # ── национальные движения
    ("national", 6, r"Украинск\w+ Народн\w+ Республик|УНР|Директори[ияю]\b"),
    ("national", 6, r"гетман|Украинск\w+ держав"),
    ("national", 6, r"Алаш"),
    ("national", 6, r"Грузинск\w+ Демократическ\w+|Закавказск\w+ комиссариат"),
    ("national", 6, r"Латвийск\w+ Республик|Латышск\w+ крестьянск\w+ союз"),
    ("national", 6, r"Эстони|Эстляндск\w+ Республик|Премьер-министр Эстонии"),
    ("national", 6, r"Королевств\w+ Финляндия|Финляндск\w+ Республик"),
    ("national", 6, r"младобухарц|Бухарск\w+ Народн\w+"),
    ("national", 6, r"Кубанск\w+ народн\w+ республик"),
    ("national", 6, r"Армянск\w+ Республик|Дашнакцутюн|Мусават"),
    ("national", 6, r"Государства Польского|Польск\w+ Республик|Речи Посполитой"),
    ("national", 3, r"автономи[ияю]|национальн\w+ движени"),
    # ── зелёные и повстанцы
    ("green", 6, r"анархист|махновск|Махно"),
    ("green", 6, r"басмач"),
    ("green", 6, r"повстанческ\w+ арми|зелён\w+"),
    ("green", 3, r"Атаман Херсонщины|атаманщин"),
]

_COMPILED = [(camp, w, re.compile(pat, re.IGNORECASE)) for camp, w, pat in RULES]

# Регалии весомее биографии: биография перечисляет всех, с кем человек
# пересекался, и по ней Деникин «состоит» во Временном правительстве.
W_FIRST = 5      # первая строка регалий — главная роль, так помечено в докс
W_REGALIA = 3
W_SUMMARY = 1
SUMMARY_HEAD = 700   # первый абзац биографии, дальше идут поздние годы
MARGIN = 1.4         # во сколько раз победитель обязан обойти второго


def classify(regalia: List[str], summary: Optional[str]) -> dict:
    """→ {camp, scores, evidence}. `camp` = None, если уверенности нет."""
    scores: Dict[str, int] = {c: 0 for c in CAMPS}
    evidence: Dict[str, List[str]] = {c: [] for c in CAMPS}

    reg = list(regalia or [])
    # Первый пункт регалий — та роль, ради которой человек в экспозиции.
    # У Егорова это «один из организаторов РККА», а «член партий эсеров,
    # левых эсеров и большевиков» ниже — биография партийных метаний,
    # и без разделения весов она перетягивает его в революционную демократию.
    first_text = reg[0] if reg else ""
    rest_text = "\n".join(reg[1:])
    sum_text = (summary or "")[:SUMMARY_HEAD]

    for text, weight in ((first_text, W_FIRST), (rest_text, W_REGALIA),
                         (sum_text, W_SUMMARY)):
        if not text:
            continue
        for camp, w, rx in _COMPILED:
            hits = rx.findall(text)
            if hits:
                scores[camp] += w * weight * min(len(hits), 2)
                if weight == W_REGALIA and rx.pattern not in evidence[camp]:
                    evidence[camp].append(rx.pattern)

    ranked = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)
    top, top_score = ranked[0]
    second_score = ranked[1][1] if len(ranked) > 1 else 0

    camp = None
    if top_score > 0 and (second_score == 0 or top_score >= second_score * MARGIN):
        camp = top
    return {"camp": camp, "scores": scores, "evidence": evidence.get(top or "", [])}
