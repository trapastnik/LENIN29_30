// Масштаб киоска для разделов сцены.
//
// Размеры в JSX — обычные числа, на --ui-scale они сами не отреагируют:
// это не CSS, а значения инлайн-стиля. Пропускаем их через S(), и раздел
// растёт вместе с остальным интерфейсом.
//
// Зачем. /expo/ живёт на приколотом --ui-scale: 1, потому что ГЛАВНАЯ
// масштабирует канвас сама (transform: scale). Но «Персоналии» и «Хроника» —
// обычные прокручиваемые страницы без канваса, и на 4K они шли в одинарном
// размере, пока всё вокруг удваивалось. Замер на stage, 3840×2160:
// 17 колонок карточек вместо семи, «к экспозиции» 120 физических пикселей
// против 240 на главной.
//
// ⚠️ Главный экран этот файл НЕ подключает и подключать не должен: там канвас
// уже масштабируется, и второе умножение дало бы четырёхкратное.
//
// Запас `1` обязателен: без него calc невалиден на этапе вычисления, и
// правило отбрасывается ЦЕЛИКОМ, а не откатывается к значению по умолчанию.
//
// Не масштабируем: толщину линий, скругления-капсулы, трекинг в em,
// z-index, прозрачность — им удвоение только вредит.

function S(v) {
  return typeof v === 'number'
    ? `calc(${v}px * var(--ui-scale, 1))`
    : String(v).replace(/(\d+(?:\.\d+)?)px/g, (_, n) => `calc(${n}px * var(--ui-scale, 1))`);
}

window.MTK_S = S;
