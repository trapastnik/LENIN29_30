// Глубокие ссылки: открыть карточку по адресу вида `<страница>.html#card=<id>`.
//
// ЗАЧЕМ. Разделы разведены по четырём страницам, внутри страницы карточка
// открывается модалкой, а между страницами механизма не было вовсе. Из 743
// связей в справках 485 (65 %) ведут на карточку ЧУЖОЙ страницы — блок
// «связанные справки», свёрстанный без этого, дал бы две трети мёртвых
// кнопок: посетитель жмёт, ничего не происходит, и он не понимает почему.
// Тем же приёмом открываются 77 переходов хроники на карточки событий.
//
// ФОРМА (согласована с оркестратором до реализации):
//
// 1. `#card=<id>`, а не `#/party/<id>`. Второй вид ОБЕЩАЕТ маршрутизацию,
//    которой у нас нет: через месяц кто-то напишет `#/person/lenin`
//    на странице партий и будет прав по виду адреса. Тип в адресе
//    избыточен — страница уже говорит, карточки какого рода на ней.
//
// 2. Карточки нет — раздел открывается нормально, сверху видимая плашка.
//    Молчание это та же мёртвая кнопка, только без кнопки.
//
// 3. ⚠️ Хэш стирается СРАЗУ после чтения. Это не про длину истории:
//    посетитель пришёл по ссылке и ушёл, стенд сбросил сеанс перезагрузкой —
//    и открыл ТУ ЖЕ чужую справку следующему человеку. Адрес переживает
//    посетителя, а не должен. `replaceState` снимает это независимо от того,
//    чем зона `kiosk` делает сброс.
//
// Внутри страницы хэш НЕ ТРОГАЕМ: карточка открывается напрямую. Иначе
// десятки открытий за сеанс плодили бы записи истории на ровном месте.
// Поэтому же не нужен `hashchange` — меняться нечему.

/** Достаёт id из `#card=<id>`. Пусто и мусор — одинаково null. */
export function readCardId(hash = location.hash) {
  const m = String(hash || '').match(/^#card=([A-Za-z0-9_-]+)$/);
  return m ? m[1] : null;
}

/**
 * Стирает хэш, не трогая путь и не добавляя записи в историю.
 * Вызывать сразу после чтения — до того, как карточка открылась.
 */
export function clearHash() {
  if (!location.hash) return;
  history.replaceState(null, '', location.pathname + location.search);
}

/**
 * Показывает плашку «Справка не найдена» поверх раздела.
 * Раздел при этом работает: посетитель видит, что его перевели куда надо,
 * и может пользоваться дальше.
 */
export function showMissing(id, lang = 'ru') {
  const прежняя = document.getElementById('deep-link-missing');
  if (прежняя) прежняя.remove();

  const el = document.createElement('div');
  el.id = 'deep-link-missing';
  el.setAttribute('role', 'status');
  el.textContent = lang === 'en'
    ? `Dossier not found: ${id}`
    : `Справка не найдена: ${id}`;

  const кнопка = document.createElement('button');
  кнопка.type = 'button';
  кнопка.className = 'back-link';
  кнопка.textContent = lang === 'en' ? 'Close' : 'Закрыть';
  кнопка.addEventListener('click', () => el.remove());
  el.appendChild(кнопка);

  document.body.appendChild(el);
}

/**
 * Полный приём для страницы: прочитать адрес, найти запись, открыть.
 *
 * @param {Array}    items  записи раздела из `_index.json`
 * @param {Function} open   то же, чем страница открывает карточку по тапу.
 *                          Именно то же: отдельный путь отрисовки — это
 *                          вторая правда о том, как выглядит карточка.
 * @param {string}   lang   язык для плашки
 * @returns {boolean} открыли ли карточку
 */
export function openFromHash(items, open, lang = 'ru') {
  const id = readCardId();
  if (!id) return false;

  clearHash();          // до открытия: дальше может быть что угодно, адрес уже чист
  const item = (items || []).find((i) => i && i.id === id);
  if (!item) { showMissing(id, lang); return false; }

  open(item);
  return true;
}
