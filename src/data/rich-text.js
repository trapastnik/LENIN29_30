// Разметка в текстах импорта — строковая версия, для карточек на веб-компонентах.
//
// Импорт кладёт в summary_ru ссылки на другие справки —
// `[большевиков](#/party/bolsheviks)`, а неразрезолвленные упоминания
// помечает `***жирным курсивом***` (docs/content.md). Без разбора это видно
// на экране как есть, квадратными скобками: на 2026-08-04 в разделах
// «Партии» и «Государственные образования» так выводилось 1197 ссылок
// в 91 справке из 92.
//
// Почему отдельный файл, а не общий с public/expo/rich-text.jsx: тот отдаёт
// React-узлы для сцены, а <party-card>/<state-card> собирают HTML строкой.
// Разметка одна, представления два — держим их рядом по смыслу и врозь
// по механике.
//
// ⚠️ Переходов по ссылкам здесь НЕТ, и это решение, а не недоделка. Часть
// ссылок ведёт на сущности другого раздела (в справках партий полно ссылок
// на гособразования и наоборот), поэтому «открыть в том же разделе» не
// работает — нужен роутер поверх iframe-оверлеев. Пока термин подсвечен
// так же, как в сцене: единообразие важнее половинчатой функции.

const RICH = /\[([^\]]+)\]\(([^)]+)\)|(\*\*\*)([^*]+)\3|(\*\*)([^*]+)\5|(\*)([^*]+)\7/g;

/**
 * Экранирование под innerHTML. Тексты справок приходят из docx заказчика,
 * и `<` там встречается: без экранирования кусок текста молча исчезнет,
 * приняв вид тега.
 */
export function escapeHtml(src) {
  return String(src == null ? '' : src)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Разбирает разметку в HTML-строку. Экранирует всё, что не разметка.
 * @param {string} src исходный текст справки
 * @returns {string} готовый HTML
 */
export function richTextHtml(src) {
  const s = String(src == null ? '' : src);
  let out = '';
  let last = 0;
  let m;
  RICH.lastIndex = 0;
  while ((m = RICH.exec(s)) !== null) {
    if (m.index > last) out += escapeHtml(s.slice(last, m.index));
    if (m[1] !== undefined) {
      // Ссылка на другую справку — подсвеченный термин, не кнопка.
      out += `<span class="rt-ref">${escapeHtml(m[1])}</span>`;
    } else if (m[3]) {
      // Неразрезолвленное упоминание: курсива не даём — на Nolde его нет,
      // а разнобой между разделами хуже, чем ровный полужирный (§8).
      out += `<b class="rt-unresolved">${escapeHtml(m[4])}</b>`;
    } else if (m[5]) {
      out += `<b>${escapeHtml(m[6])}</b>`;
    } else {
      out += `<b class="rt-em">${escapeHtml(m[8])}</b>`;
    }
    last = m.index + m[0].length;
  }
  if (last < s.length) out += escapeHtml(s.slice(last));
  return out;
}

/**
 * Текст справки в абзацы. Пустая строка — разделитель, как в импорте.
 */
export function richParagraphs(src) {
  return String(src == null ? '' : src)
    .split(/\n\s*\n/)
    .map(p => p.trim())
    .filter(Boolean)
    .map(p => `<p>${richTextHtml(p)}</p>`)
    .join('');
}

// Стилей здесь намеренно нет. Классы .rt-ref / .rt-unresolved / .rt-em
// оформляет тот компонент, который их показывает: цвет берётся из
// --camp-ink, а это свойство ставится на элемент из JS, и правило должно
// лежать рядом с ним. Разметка общая, оформление — местное.
